from typing import Annotated
from uuid import UUID

from fastapi import APIRouter, Depends, Path, Query

from api.dependencies import (
    get_block_account,
    get_create_account,
    get_get_account,
    get_get_account_by_number,
    get_list_accounts,
    get_reactivate_account,
)
from api.schemas.account import (
    AccountCreateRequest,
    AccountListResponse,
    AccountPagination,
    AccountResponse,
    ErrorResponse,
)
from application.account_messages import (
    BlockAccountCommand,
    CreateAccountCommand,
    GetAccountByNumberQuery,
    GetAccountQuery,
    ListAccountsQuery,
    ReactivateAccountCommand,
)
from application.use_cases.block_account import BlockAccount
from application.use_cases.create_account import CreateAccount
from application.use_cases.get_account import GetAccount
from application.use_cases.get_account_by_number import GetAccountByNumber
from application.use_cases.list_accounts import ListAccounts
from application.use_cases.reactivate_account import ReactivateAccount

router = APIRouter(
    prefix="/accounts",
    tags=["Accounts"],
    responses={
        422: {"model": ErrorResponse, "description": "Invalid request or account data"},
        500: {"model": ErrorResponse, "description": "Unexpected internal error"},
        503: {"model": ErrorResponse, "description": "Persistence unavailable"},
    },
)


@router.post(
    "",
    status_code=201,
    response_model=AccountResponse,
    responses={409: {"model": ErrorResponse, "description": "Account number conflict"}},
)
def create_account(
    payload: AccountCreateRequest,
    use_case: Annotated[CreateAccount, Depends(get_create_account)],
) -> AccountResponse:
    """Open an ACTIVE SAVINGS_ACCOUNT. Customer existence is not yet checked in CRP.

    Numbers are internal references, not IBANs. UUID, number, product and status
    are generated by the application/domain and cannot be supplied in the request.
    """
    account = use_case.execute(CreateAccountCommand(**payload.model_dump()))
    return AccountResponse.model_validate(account)


@router.get("", response_model=AccountListResponse)
def list_accounts(
    use_case: Annotated[ListAccounts, Depends(get_list_accounts)],
    customer_id: UUID | None = None,
    limit: Annotated[int, Query(ge=1, le=100, description="Maximum items, 1–100")] = 50,
    offset: Annotated[int, Query(ge=0, description="Number of matching items to skip")] = 0,
) -> AccountListResponse:
    """List accounts ordered by UUID, optionally filtered by customer, with matching totals."""
    items, total = use_case.execute_with_total(ListAccountsQuery(customer_id, limit, offset))
    return AccountListResponse(
        items=[AccountResponse.model_validate(item) for item in items],
        pagination=AccountPagination.from_total(limit, offset, total),
    )


@router.get(
    "/by-number/{account_number}",
    response_model=AccountResponse,
    responses={404: {"model": ErrorResponse, "description": "Account not found"}},
)
def get_account_by_number(
    account_number: Annotated[str, Path(min_length=1, pattern=r"\S")],
    use_case: Annotated[GetAccountByNumber, Depends(get_get_account_by_number)],
) -> AccountResponse:
    """Retrieve by exact account number, preserving its formatting."""
    return AccountResponse.model_validate(use_case.execute(GetAccountByNumberQuery(account_number)))


@router.get(
    "/{account_id}",
    response_model=AccountResponse,
    responses={404: {"model": ErrorResponse, "description": "Account not found"}},
)
def get_account(
    account_id: UUID,
    use_case: Annotated[GetAccount, Depends(get_get_account)],
) -> AccountResponse:
    """Retrieve an account by UUID, including historical CLOSED accounts."""
    return AccountResponse.model_validate(use_case.execute(GetAccountQuery(account_id)))


@router.patch(
    "/{account_id}/block",
    response_model=AccountResponse,
    responses={
        404: {"model": ErrorResponse, "description": "Account not found"},
        409: {"model": ErrorResponse, "description": "Only ACTIVE accounts can be blocked"},
    },
)
def block_account(
    account_id: UUID,
    use_case: Annotated[BlockAccount, Depends(get_block_account)],
) -> AccountResponse:
    """Block an ACTIVE account. Other states cause a conflict."""
    return AccountResponse.model_validate(use_case.execute(BlockAccountCommand(account_id)))


@router.patch(
    "/{account_id}/reactivate",
    response_model=AccountResponse,
    responses={
        404: {"model": ErrorResponse, "description": "Account not found"},
        409: {"model": ErrorResponse, "description": "Only BLOCKED accounts can be reactivated"},
    },
)
def reactivate_account(
    account_id: UUID,
    use_case: Annotated[ReactivateAccount, Depends(get_reactivate_account)],
) -> AccountResponse:
    """Reactivate a BLOCKED account. ACTIVE and CLOSED accounts cause a conflict."""
    return AccountResponse.model_validate(use_case.execute(ReactivateAccountCommand(account_id)))
